// <regex>

// class regex_token_iterator<BidirectionalIterator, charT, traits>

// bool operator==(const regex_token_iterator& right) const;
// bool operator==(default_sentinel_t) const { return *this == regex_token_iterator(); } // since C++20
// bool operator!=(const regex_token_iterator& right) const; // generated by the compiler in C++20

#include <libstud/regex.hxx>

#include <iterator>

#include "test_comparisons.hxx"
#include "test_macros.hxx"

#undef NDEBUG
#include <cassert>

using namespace stud::regex;

using std::begin;
using std::end;

#ifdef __cpp_lib_ranges
using std::default_sentinel;
#endif

int main(int, char**) {
#ifdef __cpp_lib_ranges
  AssertEqualityReturnBool<cregex_token_iterator>();

  {
    cregex_token_iterator i;
    assert(testEquality(i, default_sentinel, true));
  }

  AssertEqualityReturnBool<sregex_token_iterator>();

  {
    sregex_token_iterator i;
    assert(testEquality(i, default_sentinel, true));
  }
#endif

  {
    regex phone_numbers("\\d{3}-\\d{4}");
    const char phone_book[] = "start 555-1234, 555-2345, 555-3456 end";
    cregex_token_iterator i(begin(phone_book), end(phone_book) - 1, phone_numbers, -1);
    assert(i != cregex_token_iterator());
    assert(!(i == cregex_token_iterator()));
    cregex_token_iterator i2 = i;
    assert(i2 == i);
    assert(!(i2 != i));
    ++i;
    assert(!(i2 == i));
    assert(i2 != i);
  }

  return 0;
}
